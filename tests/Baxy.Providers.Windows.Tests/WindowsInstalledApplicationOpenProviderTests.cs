    private static ApplicationOpenRequest Request(string name) =>
        new(name, Guid.NewGuid().ToString("D"));

    private static InstalledApplicationObservation Observation(bool foreground) =>
        new(
            ProcessId: 4242,
            ProcessCreationTimeUtcTicks: DateTime.UtcNow.Ticks,
            ExecutablePath: @"C:\Program Files (x86)\Steam\steam.exe",
            WindowHandle: 73,
            Visible: true,
            Foreground: foreground);

    private sealed class FakePlatform(IReadOnlyList<InstalledApplicationEntry> catalog)
        : IInstalledApplicationPlatform
    {
        private long? _requestedForegroundHandle;

        public IReadOnlyList<InstalledApplicationObservation> Observations { get; set; } = [];

        public Func<
            InstalledApplicationEntry,
            IReadOnlyList<InstalledApplicationObservation>>
            ? InventoryResolver
        { get; init; }

        public InstalledApplicationObservation? ObservationAfterActivation { get; init; }

        public bool FocusRequiresDelay { get; init; }

        public int ActivateCalls { get; private set; }

        public int FocusCalls { get; private set; }

        public int DelayCalls { get; private set; }

        public int InventoryCalls { get; private set; }

        public Exception? CatalogFailure { get; init; }

        public ValueTask<IReadOnlyList<InstalledApplicationEntry>> ReadCatalogAsync(
            CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (CatalogFailure is not null)
            {
                return ValueTask.FromException<IReadOnlyList<InstalledApplicationEntry>>(
                    CatalogFailure);
            }

            return ValueTask.FromResult(catalog);
        }

        public IReadOnlyList<InstalledApplicationObservation> Inventory(
            InstalledApplicationEntry entry)
        {
            InventoryCalls++;
            return InventoryResolver?.Invoke(entry) ?? Observations;
        }

        public bool Activate(InstalledApplicationEntry entry)
        {
            ActivateCalls++;
            if (ObservationAfterActivation is not null)
            {
                Observations = [ObservationAfterActivation];
            }

            return true;
        }

        public void RequestForeground(long windowHandle)
        {
            FocusCalls++;
            _requestedForegroundHandle = windowHandle;
            if (!FocusRequiresDelay)
            {
                MarkForeground(windowHandle);
            }
        }

        public ValueTask DelayAsync(TimeSpan delay, CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            DelayCalls++;
            if (FocusRequiresDelay && _requestedForegroundHandle is long windowHandle)
            {
                MarkForeground(windowHandle);
            }
            return ValueTask.CompletedTask;
        }

        private void MarkForeground(long windowHandle)
        {
            Observations = Observations
                .Select(item => item.WindowHandle == windowHandle
                    ? item with { Foreground = true }
                    : item)
                .ToArray();
        }
    }
