    [Test]
    public void CatalogSnapshotTruncatesDeterministicallyAtTheContractLimit()
    {
        InstalledApplicationEntry[] catalog = Enumerable
            .Range(0, ApplicationCatalogContract.MaximumNames + 2)
            .Select(static index => new InstalledApplicationEntry(
                $"Application {index:D4}",
                $"Contoso.Application.{index:D4}"))
            .ToArray();

        InstalledApplicationCatalogSnapshot snapshot =
            WindowsInstalledApplicationOpenProvider.CreateCatalogSnapshot(catalog);

        Assert.Multiple(() =>
        {
            Assert.That(snapshot.Verified, Is.True);
            Assert.That(snapshot.Complete, Is.False);
            Assert.That(
                snapshot.Names,
                Has.Count.EqualTo(ApplicationCatalogContract.MaximumNames));
            Assert.That(
                snapshot.Names
                    .Select(ApplicationCatalogContract.NormalizeName)
                    .Distinct(StringComparer.Ordinal)
                    .Count(),
                Is.EqualTo(snapshot.Names.Count));
        });
    }

