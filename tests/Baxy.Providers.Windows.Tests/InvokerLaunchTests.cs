using Baxy.Providers.Windows.Applications;
using NUnit.Framework;

namespace Baxy.Providers.Windows.Tests;

// v3 r5a M5: a program Windows raises to administrator unasked is started with the person's own rights; the rule is
// the executable's manifest, never a list of programs.
[TestFixture]
public sealed class InvokerLaunchTests
{
    private const string Tool = @"C:\Windows\system32\tool.exe";

    private static string Manifest(string level, string? autoElevate = null) =>
        "<assembly xmlns=\"urn:schemas-microsoft-com:asm.v1\"><trustInfo><security><requestedPrivileges>"
        + $"<requestedExecutionLevel level=\"{level}\" uiAccess=\"false\"/>"
        + "</requestedPrivileges></security></trustInfo>"
        + (autoElevate is null ? string.Empty
            : $"<asmv3:application><asmv3:windowsSettings><autoElevate xmlns=\"http://schemas.microsoft.com/SMI/2005/WindowsSettings\">{autoElevate}</autoElevate></asmv3:windowsSettings></asmv3:application>")
        + "</assembly>";

    private static InvokerLaunch.LaunchPlan? Plan(InstalledApplicationEntry entry, string? manifest) =>
        InvokerLaunch.Plan(
            entry,
            static _ => true,
            static extension => extension == ".msc" ? "%SystemRoot%\\system32\\console.exe \"%1\" %*" : null,
            _ => manifest);

    [Test]
    public void HighestAvailableStartsWithoutRaising()
    {
        var entry = new InstalledApplicationEntry("Tool", "Microsoft.AutoGenerated.{1}", Tool, "/7");

        InvokerLaunch.LaunchPlan? plan = Plan(entry, Manifest("highestAvailable"));

        Assert.That(plan, Is.Not.Null);
        Assert.That(plan!.Executable, Is.EqualTo(Tool));
        Assert.That(plan.Arguments, Is.EqualTo("/7"));
    }

    [Test]
    public void AutoElevateOnAnInvokerManifestStartsWithoutRaising()
    {
        var entry = new InstalledApplicationEntry("Tool", "Microsoft.AutoGenerated.{2}", Tool);

        Assert.That(Plan(entry, Manifest("asInvoker", "true")), Is.Not.Null);
    }

    [Test]
    public void RequireAdministratorKeepsTheShellPath()
    {
        // A program that cannot run without the rights is left to Windows, which asks the person (limit as before).
        var entry = new InstalledApplicationEntry("Tool", "Microsoft.AutoGenerated.{3}", Tool);

        Assert.That(Plan(entry, Manifest("requireAdministrator", "true")), Is.Null);
    }

    [Test]
    public void AnOrdinaryProgramKeepsTheShellPath()
    {
        var entry = new InstalledApplicationEntry("Editor", "Microsoft.AutoGenerated.{4}", Tool);

        Assert.That(Plan(entry, Manifest("asInvoker")), Is.Null);
        Assert.That(Plan(entry, null), Is.Null, "a program without a manifest runs as the person anyway");
    }

    [Test]
    public void APackagedApplicationIsNeverStartedThisWay()
    {
        var entry = new InstalledApplicationEntry("Store app", "Vendor.App_0123456789abc!App", Tool);

        Assert.That(Plan(entry, Manifest("highestAvailable")), Is.Null);
    }

    [Test]
    public void AConsoleDocumentIsStartedByItsAssociatedProgramWithTheShortcutArguments()
    {
        var entry = new InstalledApplicationEntry(
            "Console view", @"Microsoft.AutoGenerated.{5}", @"C:\Windows\system32\view.msc", "/s");

        InvokerLaunch.LaunchPlan? plan = Plan(entry, Manifest("highestAvailable"));

        Assert.That(plan, Is.Not.Null);
        Assert.That(plan!.Executable, Is.EqualTo(Environment.ExpandEnvironmentVariables(@"%SystemRoot%\system32\console.exe")));
        Assert.That(plan.Arguments, Is.EqualTo("\"C:\\Windows\\system32\\view.msc\" /s"));
    }

    [Test]
    public void ADocumentWithoutAnAssociationKeepsTheShellPath()
    {
        var entry = new InstalledApplicationEntry("Notes", "Microsoft.AutoGenerated.{6}", @"C:\Users\x\notes.unknownext");

        Assert.That(Plan(entry, Manifest("highestAvailable")), Is.Null);
    }

    [Test]
    public void TheManifestReaderReadsTheLevelAndTheAutoElevateFlag()
    {
        InvokerLaunch.ManifestElevation raised = InvokerLaunch.ParseManifest(Manifest("highestAvailable", "true"));
        InvokerLaunch.ManifestElevation plain = InvokerLaunch.ParseManifest(Manifest("asInvoker", "false"));

        Assert.That(raised.Level, Is.EqualTo("highestAvailable"));
        Assert.That(raised.AutoElevate, Is.True);
        Assert.That(raised.RaisesUnasked, Is.True);
        Assert.That(plain.RaisesUnasked, Is.False);
    }

    // Review of M5: the core runs in the App's kill-on-close job. The program leaves the job (it outlives BAXY and a
    // restart of the core) and inherits none of the core's handles (its stdio pipes), like WindowsApplicationLauncher.
    [Test]
    public void TheProgramLeavesTheJobInheritsNoHandleAndRunsAsInvoker()
    {
        var plan = new InvokerLaunch.LaunchPlan(Tool, "\"C:\\Windows\\system32\\view.msc\" /s", @"C:\Windows\system32");
        var environment = new System.Collections.Hashtable
        {
            ["Path"] = @"C:\Windows",
            ["__COMPAT_LAYER"] = "HighDpiAware",
            ["TEMP"] = @"C:\Temp",
        };

        InvokerLaunch.StartRequest request = InvokerLaunch.Prepare(plan, environment);

        Assert.Multiple(() =>
        {
            Assert.That(request.CreationFlags, Is.EqualTo(WindowsApplicationLauncher.CreateBreakawayFromJob | 0x00000400u));
            Assert.That(request.InheritHandles, Is.False);
            Assert.That(request.CommandLine, Is.EqualTo("\"" + Tool + "\" \"C:\\Windows\\system32\\view.msc\" /s"));
            Assert.That(request.WorkingDirectory, Is.EqualTo(@"C:\Windows\system32"));
            Assert.That(
                request.EnvironmentBlock,
                Is.EqualTo("Path=C:\\Windows\0TEMP=C:\\Temp\0__COMPAT_LAYER=RunAsInvoker\0\0"),
                "the core's environment, the person's layer replaced by RunAsInvoker, sorted and double-terminated");
        });
    }

    [Test]
    public void AProgramWithoutArgumentsGetsOnlyItsQuotedPath()
    {
        InvokerLaunch.StartRequest request = InvokerLaunch.Prepare(
            new InvokerLaunch.LaunchPlan(Tool, string.Empty, @"C:\Windows\system32"), new System.Collections.Hashtable());

        Assert.That(request.CommandLine, Is.EqualTo("\"" + Tool + "\""));
        Assert.That(request.EnvironmentBlock, Is.EqualTo("__COMPAT_LAYER=RunAsInvoker\0\0"));
    }

    // Review of M5: the limit of an elevated window offers to reopen it unraised only for a program that stays so. The
    // Task Manager (asInvoker with autoElevate) and the performance monitor (highestAvailable with autoElevate) raised
    // themselves again, measured live; the consoles (highestAvailable alone) did not.
    [TestCase("highestAvailable", null, true)]
    [TestCase("highestAvailable", "false", true)]
    [TestCase("highestAvailable", "true", false)]
    [TestCase("asInvoker", "true", false)]
    [TestCase("asInvoker", null, false)]
    [TestCase("requireAdministrator", null, false)]
    public void OnlyAProgramThatStaysUnraisedIsOfferedToReopen(string level, string? autoElevate, bool reopens)
    {
        Assert.That(InvokerLaunch.ParseManifest(Manifest(level, autoElevate)).ReopensUnraised, Is.EqualTo(reopens));
    }

    [Test]
    public void ThisMachinesTaskManagerIsNeverOfferedAndItsConsoleHostIs()
    {
        string taskManager = Path.Combine(Environment.SystemDirectory, "Taskmgr.exe");
        string consoleHost = Path.Combine(Environment.SystemDirectory, "mmc.exe");
        Assume.That(File.Exists(taskManager) && File.Exists(consoleHost), Is.True);

        Assert.Multiple(() =>
        {
            Assert.That(InvokerLaunch.ParseManifest(InvokerLaunch.ReadManifest(taskManager)).ReopensUnraised, Is.False);
            Assert.That(InvokerLaunch.ParseManifest(InvokerLaunch.ReadManifest(consoleHost)).ReopensUnraised, Is.True);
        });
    }

    [Test]
    public void AWindowThatCannotBeReadIsNeverOfferedToReopen()
    {
        Assert.That(InvokerLaunch.WindowReopensUnraised(0), Is.False);
        Assert.That(InvokerLaunch.WindowReopensUnraised(-1), Is.False);
    }

    // Review of cu-v3-elevacion (finding 6): the platform's own check (process token and manifest, no fake). This test
    // process runs at its own level (not above itself), and a process that cannot be read is never raised: the opening
    // reuses them as before. Reads only; nothing is started.
    [Test]
    public void TheRealPlatformNeverCallsAProcessAtItsOwnLevelRaised()
    {
        var platform = new WindowsInstalledApplicationPlatform();

        Assert.Multiple(() =>
        {
            Assert.That(platform.RaisedButReopensUnraised(Environment.ProcessId), Is.False);
            Assert.That(platform.RaisedButReopensUnraised(0), Is.False);
            Assert.That(platform.RaisedButReopensUnraised(-1), Is.False);
        });
    }

    [Test]
    public void TheRealManifestOfThisMachinesConsoleHostIsRead()
    {
        // The reader against a real executable: the system's console host declares a manifest.
        string? manifest = InvokerLaunch.ReadManifest(Path.Combine(Environment.SystemDirectory, "mmc.exe"));
        Assert.That(manifest, Is.Not.Null);
        Assert.That(InvokerLaunch.ParseManifest(manifest).Level, Is.Not.Null.And.Not.Empty);
    }
}
