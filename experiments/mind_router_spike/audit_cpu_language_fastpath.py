"""CPU-only audit of possible response-language fast paths for BAXY.

This is a research harness, not production runtime code.  It does not start
llama.cpp, load Torch, use a GPU, install dependencies, or mutate registered
assets.  Its central distinction is intentional:

* ``historical_messages.jsonl`` is broad, but its ``language`` field is partly
  generated by the small regex classifier in ``build_historical_corpus.py``.
  It is useful for measuring parity, not for proving the current runtime
  ``es/en/mixed`` contract.
* The reviewed probes below exercise the current contract, including unknown
  English words embedded in Spanish and proper names that must not count as a
  second language.

Every selective detector returns ``None`` when it abstains.  A production
fast path would be allowed to skip L only for non-``None`` results.
"""

